def normalize(q: str) -> str:
    q = re.sub(r"\[[^\]]*\]", " ", str(q))            # [전화] 같은 마스킹 표시는 뺌
    q = re.sub(r"\s+", " ", q).strip()
    for k in sorted(ABBR_DICT, key=len, reverse=True):
        q = q.replace(k, ABBR_DICT[k])
    return q


def kw_hits(text: str, kw: dict[str, list[str]]) -> dict[str, int]:
    out = {k: sum(w in text for w in words) for k, words in kw.items()}
    return {k: v for k, v in out.items() if v}


def extract_slots(text: str) -> dict[str, str]:
    return {slot: val for slot, vals in SLOT_DICT.items() for val, words in vals.items() if any(w in text for w in words)}


def topic_words(text: str) -> list[str]:
    return [w for words in CATEGORY_KEYWORDS.values() for w in words if w in text]


def expansions(text: str) -> list[str]:
    """사전에 있는 말만 덧붙여요. 사전에 없는 정보는 만들지 않아요."""
    adds = [v for k, v in TERM_DICT.items() if k in text] + list(extract_slots(text).values())
    out: list[str] = []
    for a in adds:
        if a not in text and a not in out:
            out.append(a)
    return out


# ───────── 형태소 분석 (BM25용) ─────────
_KIWI = None
_KEEP = {"NNG", "NNP", "NNB", "NR", "SL", "SN", "SH", "XR", "VV", "VA"}
_WORD = re.compile(r"[가-힣]+|[A-Za-z]+|\d+")


def _kiwi():
    global _KIWI
    if _KIWI is None:
        try:
            from kiwipiepy import Kiwi
            _KIWI = Kiwi()
        except Exception:
            _KIWI = False
    return _KIWI


def tokenizer_name() -> str:
    return "kiwi" if _kiwi() else "bigram"


def tokenize(text: str) -> list[str]:
    """kiwi가 있으면 명사·동사 어간, 없으면 한글 2글자 묶음으로 나눠요."""
    k = _kiwi()
    if k:
        return [t.form.lower() for t in k.tokenize(text) if t.tag in _KEEP and (len(t.form) > 1 or t.tag in ("SN", "NNG"))]
    out = []
    for w in _WORD.findall(text):
        if re.match(r"[가-힣]", w) and len(w) > 2:
            out += [w[i:i + 2] for i in range(len(w) - 1)]
        else:
            out.append(w.lower())
    return out
